/// The built-in bitmap for `ch`, if there is one.
pub(crate) fn builtin(ch: char) -> Option<&'static [u8; 16]> {
    GLYPHS
        .binary_search_by_key(&ch, |&(c, _)| c)
        .ok()
        .map(|i| &GLYPHS[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cli_r18_builtin_glyphs_are_sorted_unique_and_not_blank() {
        for pair in GLYPHS.windows(2) {
            assert!(pair[0].0 < pair[1].0, "{} then {}", pair[0].0, pair[1].0);
        }
        for (ch, rows) in GLYPHS {
            assert!(rows.iter().any(|&r| r != 0), "{ch} is blank");
            assert_eq!(builtin(*ch), Some(rows));
        }
        assert_eq!(builtin('a'), None);
    }
}
