//! Built-in 8 × 16 bitmaps for the glyphs scenes use that `font8x8` lacks (CLI-R18).
//!
//! Each bitmap is drawn at the cell's full resolution (one bit per pixel, bit 0 = leftmost),
//! shaped to read like the terminal glyph at that size: `●` a filled disc, `•` a small centred
//! dot, arrows and bars two pixels thick like the doubled `font8x8` glyphs around them. The
//! vertical centre of a cell is between rows 7 and 8.

/// One glyph: `rows` drawn from row `top` down, `#` lit and `.` dark, eight columns each.
const fn art(top: usize, rows: &[&str]) -> [u8; 16] {
    let mut out = [0u8; 16];
    let mut r = 0;
    while r < rows.len() {
        let bytes = rows[r].as_bytes();
        assert!(bytes.len() == 8, "a glyph row is eight columns");
        assert!(top + r < 16, "a glyph is sixteen rows");
        let mut c = 0;
        while c < 8 {
            match bytes[c] {
                b'#' => out[top + r] |= 1 << c,
                b'.' => {}
                _ => panic!("a glyph row is `#` and `.` only"),
            }
            c += 1;
        }
        r += 1;
    }
    out
}

