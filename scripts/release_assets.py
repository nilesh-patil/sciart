#!/usr/bin/env python3
"""Release assets (SPEC-008 DIST-R5, DIST-R6).

Packs one tarball per target from the release binaries, plus the installer, and writes the
`SHA256SUMS` file that covers every asset:

    sciart-{version}-{target}.tar.gz
      sciart-{version}-{target}/
        sciart  README.md  LICENSE  CHANGELOG.md
        completions/sciart.bash  completions/_sciart  completions/sciart.fish
        man/sciart.1  man/sciart-<subcommand>.1 ...
    install.sh
    SHA256SUMS

The completions and manual pages are generated by a built binary (`sciart completions`,
`sciart man`, CLI-R17), the same for every target, so one binary that runs on the packing
machine (`--tool`) generates them for all. Tarballs are reproducible: sorted entries,
owner 0, fixed modes and the commit time (`SOURCE_DATE_EPOCH`) as every mtime.

    python3 scripts/release_assets.py --version 1.0.0 --bins <dir> --tool <sciart> --out <dir>

`--bins` holds `<target>/sciart` for each target to pack.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import os
import re
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# TEST-R13 / ADR-0029: the platform tiers; the release builds all six (DIST-R5).
TIER_1 = ("aarch64-apple-darwin", "x86_64-unknown-linux-gnu")
TIER_2 = ("aarch64-unknown-linux-gnu",)
TIER_3 = ("x86_64-apple-darwin", "x86_64-unknown-linux-musl", "aarch64-unknown-linux-musl")
TARGETS = TIER_1 + TIER_2 + TIER_3

DOCS = ("README.md", "LICENSE", "CHANGELOG.md")
COMPLETIONS = {"bash": "sciart.bash", "zsh": "_sciart", "fish": "sciart.fish"}
INSTALLER = "packaging/install.sh"
SUMS = "SHA256SUMS"
# A semantic version, pre-release allowed, no build metadata: it goes into file names,
# URLs and the formula (DIST-R1, DIST-R9).
SEMVER = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?$")


def asset_dir(version: str, target: str) -> str:
    return f"sciart-{version}-{target}"


def asset_name(version: str, target: str) -> str:
    return f"{asset_dir(version, target)}.tar.gz"


def man_subcommands(cli_source: str | None = None) -> list[str]:
    """The subcommands `sciart man` has a page for: the `MAN_PAGES` list of the CLI."""
    text = cli_source if cli_source is not None else (ROOT / "crates/sciart/src/cli.rs").read_text()
    found = re.search(r"const MAN_PAGES: \[&str; \d+\] = \[(.*?)\];", text, re.S)
    if found is None:
        raise ValueError("crates/sciart/src/cli.rs has no MAN_PAGES list")
    return re.findall(r'"([a-z-]+)"', found.group(1))


def generated_files(tool: Path) -> dict[str, bytes]:
    """`completions/...` and `man/...` entries, generated by running `tool`."""
    def run(*args: str) -> bytes:
        return subprocess.run([str(tool), *args], check=True, capture_output=True).stdout

    files = {f"completions/{name}": run("completions", shell) for shell, name in COMPLETIONS.items()}
    files["man/sciart.1"] = run("man")
    for sub in man_subcommands():
        files[f"man/sciart-{sub}.1"] = run("man", sub)
    empty = [name for name, data in files.items() if not data]
    if empty:
        raise ValueError(f"{tool} generated empty files: {empty}")
    return files


def pack(version: str, target: str, binary: bytes, extra: dict[str, bytes], mtime: int) -> bytes:
    """The tarball of one target, byte-for-byte reproducible."""
    top = asset_dir(version, target)
    entries = {"sciart": (binary, 0o755)}
    for doc in DOCS:
        entries[doc] = ((ROOT / doc).read_bytes(), 0o644)
    for name, data in extra.items():
        entries[name] = (data, 0o644)
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tar:
        dirs = sorted({top} | {f"{top}/{Path(n).parent}" for n in entries if "/" in n})
        for d in dirs:
            info = tarfile.TarInfo(d)
            info.type, info.mode, info.mtime = tarfile.DIRTYPE, 0o755, mtime
            tar.addfile(info)
        for name in sorted(entries):
            data, mode = entries[name]
            info = tarfile.TarInfo(f"{top}/{name}")
            info.size, info.mode, info.mtime = len(data), mode, mtime
            tar.addfile(info, io.BytesIO(data))
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode="wb", mtime=mtime, compresslevel=9) as gz:
        gz.write(raw.getvalue())
    return out.getvalue()


def sha256_sums(files: dict[str, bytes]) -> str:
    """`sha256sum` format, one line per asset, sorted by name."""
    return "".join(f"{hashlib.sha256(data).hexdigest()}  {name}\n" for name, data in sorted(files.items()))


def build(version: str, bins: Path, tool: Path, out: Path, targets: list[str], mtime: int) -> list[str]:
    extra = generated_files(tool)
    out.mkdir(parents=True, exist_ok=True)
    assets: dict[str, bytes] = {}
    for target in targets:
        binary = bins / target / "sciart"
        if not binary.is_file():
            raise FileNotFoundError(f"no binary for {target}: {binary}")
        assets[asset_name(version, target)] = pack(version, target, binary.read_bytes(), extra, mtime)
    assets["install.sh"] = (ROOT / INSTALLER).read_bytes()
    for name, data in assets.items():
        path = out / name
        path.write_bytes(data)
        if name == "install.sh":
            path.chmod(0o755)
    (out / SUMS).write_text(sha256_sums(assets))
    return sorted(assets) + [SUMS]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", required=True)
    parser.add_argument("--bins", type=Path, required=True)
    parser.add_argument("--tool", type=Path, required=True, help="a sciart binary that runs here")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--targets", default=",".join(TARGETS),
                        help="comma-separated (default: all six release targets)")
    args = parser.parse_args()
    if not SEMVER.match(args.version):
        print(f"DIST-R5: not a semantic version: {args.version!r}", file=sys.stderr)
        return 2
    mtime = int(os.environ.get("SOURCE_DATE_EPOCH", "0"))
    targets = [t for t in args.targets.split(",") if t]
    unknown = sorted(set(targets) - set(TARGETS))
    if unknown:
        print(f"DIST-R5: not a release target: {unknown}", file=sys.stderr)
        return 2
    for name in build(args.version, args.bins, args.tool, args.out, targets, mtime):
        print(f"{args.out / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
